export function idpayMessage(status?: number, errorCode?: number): string {
  if (errorCode !== undefined && IDPAY_ERROR_MESSAGES[errorCode]) return IDPAY_ERROR_MESSAGES[errorCode]!;
  if (status !== undefined && IDPAY_STATUS_MESSAGES[status]) return IDPAY_STATUS_MESSAGES[status]!;
  return 'وضعیتِ پرداخت روشن نیست؛ اگر مبلغی کسر شده، تا پایانِ روزِ کاری به حساب شما برمی‌گردد.';
}

/** آیا این کد/وضعیت به معنایِ «پرداخت قطعی شد» است؟ */
export function idpayIsSuccess(status?: number): boolean {
  return status === 100 || status === 101 || status === 200;
}

/**
 * ماسک کردنِ شماره‌ی کارت — فقط چهار رقمِ آخر نگه داشته می‌شود.
 *
 * چرا؟ چون نگه‌داریِ شماره‌ی کاملِ کارت هم از نظرِ امنیتی خطاست و هم از نظرِ
 * قانونی (و در صورتِ نشت، بزرگ‌ترین خسارتِ اعتباری را دارد). چهار رقمِ آخر
 * برای این‌که مشتری بداند با کدام کارت پرداخته کافی است.
 */
export function maskPan(pan: string): string {
  const digits = pan.replace(/\D/g, '');
  return digits.length > 4 ? `****-****-****-${digits.slice(-4)}` : pan;
}
