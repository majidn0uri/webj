import type { SmsSendConfig } from './sms-send.js';

/** همان شمارشِ وضعیتی که `smsQueueCounts` برمی‌گرداند */
export type SmsQueueCounts = Record<string, number>;

/** برچسبِ فارسیِ سامانه‌ها — همان نام‌هایی که در پنل دیده می‌شوند */
const PROVIDER_LABELS: Record<SmsProvider, string> = {
  none: 'هیچ (فقط ثبت در صف)',
  kavenegar: 'کاوه‌نگار',
  melipayamak: 'ملی‌پیامک',
  farazsms: 'فراز اس‌ام‌اس',
};

/**
 * فاصلهٔ هر دور در حالتِ چرخه (`--loop`).
 *
 * ارقامِ فارسی پذیرفته می‌شوند (`۳۰`)، چون آدم این متغیر را از همان ترمینالی
 * می‌نویسد که گزارشِ فارسی می‌خواند. هر چیزِ بی‌معنی (`''`، `abc`) به
 * پیش‌فرض برمی‌گردد و **بی‌صدا قاطر نمی‌شود**: `0` یعنی «هیچ‌وقت دوباره
 * نبین» و `-5` یعنی چرخهٔ بی‌وقفه که پایگاه را می‌کُشد؛ هر دو در عمل پیش
 * آمده‌اند، پس این‌جا مرز دارند:
 *   • کمینهٔ ۵ ثانیه — دورِ کاملِ کارگر رویِ جعبهٔ ضعیف چند ثانیه طول می‌کشد؛
 *   • بیشینهٔ ۳۶۰۰ ثانیه — یک تایپو (`86400`) وادارت می‌کند یک روز صبر کنی،
 *     و آن «پیامکِ من دو روز است نرسیده»یِ واقعی است.
 */
export function resolveLoopIntervalMs(raw: string | undefined, fallbackSec = 60): number {
  const FALLBACK = 60;
  const MIN_SEC = 5;
  const MAX_SEC = 3600;
  const digits = String(raw ?? '').replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))).trim();
  const n = Number(digits);
  if (!Number.isFinite(n) || n <= 0) return fallbackSec * 1000 || FALLBACK * 1000;
  const clamped = Math.min(MAX_SEC, Math.max(MIN_SEC, Math.floor(n)));
  return clamped * 1000;
}

/**
 * خطوطِ وضعیت — آنچه کارگر پیش از نخستین دور چاپ می‌کند (و در حالتِ چرخه، پس از
 * هر دور که یکی از این‌ها عوض شده باشد هم بی‌فایده نیست، اما این‌جا ساده
 * نگه‌داشته‌ایم: یک‌بار، همان‌جا که آدم نگاه می‌کند).
 *
 * قاعدهٔ نگارش: هر خط یا «سبز و بی‌نیاز» است یا **علت و درمان** را با هم دارد.
 * «پیامک: خاموش» تنها، آدم را به جستجو در مستندات می‌فرستد؛ «خاموش است —
 * پنل ← تنظیمات ← پیامک» او را به مقصد می‌رساند.
 */
export function smsStateLines(cfg: SmsSendConfig, counts: SmsQueueCounts): string[] {
  const lines: string[] = [];
  const label = PROVIDER_LABELS[cfg.provider] ?? cfg.provider;
  const pending = Number(counts.pending ?? 0);
  const failed = Number(counts.failed ?? 0);
  const dead = Number(counts.dead ?? 0);
  const sent = Number(counts.sent ?? 0);
  const sending = Number(counts.sending ?? 0);

  lines.push(`پیامک: سامانه‌یِ انتخاب‌شده «${label}»، «ارسالِ پیامک» ${cfg.enabled ? 'روشن' : 'خاموش'} است.`);

  if (cfg.provider === 'none') {
    lines.push(
      '   ❌ هیچ سامانه‌ای انتخاب نشده: صف می‌پُر شود و هیچ پیامی به مشتری نمی‌رسد.',
      '   درمان: پنل ← تنظیمات ← پیامک ← سامانه (کاوه‌نگار/ملی‌پیامک/فراز) و «ارسالِ پیامک» را روشن کن.',
    );
  } else if (!cfg.enabled) {
    lines.push(
      `   ⚠️ «ارسالِ پیامک» خاموش است؛ صف دست‌نخورده می‌ماند (تلاش هم نمی‌شود، پس خطایی هم نمی‌بینی).`,
      '   درمان: همان خانه را روشن کن، یا برایِ یک دورِ دستی: `npm run worker:once` پس از روشن‌کردن.',
    );
  } else if (cfg.apiKey === '') {
    lines.push(
      `   ⚠️ «${label}» انتخاب شده ولی کلیدِ دسترسی خالی است — هر تلاش خطا می‌خورد و پیام با فاصلهٔ فزاینده دوباره در صف می‌نشیند.`,
      '   درمان: پنل ← تنظیمات ← پیامک ← «کلیدِ API». (کلید در فایلِ محیط نمی‌ماند؛ از پنل خوانده می‌شود.)',
    );
  } else if (cfg.dryRun) {
    lines.push('   ⚠️ `SMS_DRY_RUN` روشن است: هیچ درخواستی به سامانه نمی‌رود (حالتِ آزمایشِ مسیر بی‌پول).');
  } else {
    lines.push(
      `   ✅ این دور می‌فرستد. فرستنده: ${cfg.sender || 'تعیین‌نشده'} · تا ${cfg.maxAttempts} تلاش با فاصلهٔ ${cfg.backoffMinutes} دقیقه`,
    );
  }

  lines.push(
    `صف: ${pending} در انتظار` +
      (sending > 0 ? ` · ${sending} در حالِ ارسال` : '') +
      (failed > 0 ? ` · ${failed} ناموفق (دوباره تلاش می‌شود)` : '') +
      (dead > 0 ? ` · ${dead} ناامیدکننده (باید دستی بررسی شود)` : '') +
      ` · ${sent} فرستاده‌شده`,
  );

  if ((pending > 0 || failed > 0) && cfg.provider !== 'none' && cfg.enabled) {
    lines.push(`   ${pending + failed} پیام در انتظار این دور است.`);
  }
  if (pending > 0 || failed > 0) {
    lines.push(
      '   برایِ خالی‌شدنِ پیوستهٔ صف: `npm run start:worker` (یا تایمرِ systemd: `setshop-postsale.timer`).',
    );
  }

  return lines;
}
