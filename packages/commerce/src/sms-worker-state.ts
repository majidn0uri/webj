/**
 * «کارگرِ پیامک چه وضعیتی دارد؟» — دو تکهٔ منطق که بیرون از کارگر نشسته‌اند تا
 * بشود آزمایششان کرد، نه این‌که در یک اسکریپتِ اجرایی دفن شوند.
 *
 * چرا این لازم شد؟ چون «پیامک نمی‌رسد» در این سامانه **هیچ‌وقت** یک علت ندارد و
 * هیچ‌وقت هم در لاگِ سرویس نوشته نمی‌شود: یا سامانه‌ای در پنل انتخاب نشده، یا
 * «ارسالِ پیامک» خاموش است، یا کلیدِ دسترسی خالی است، یا `SMS_DRY_RUN` روشن است،
 * یا — و این رایج‌ترین است رویِ ماشینِ توسعه — **کارگری که صف را خالی می‌کند
 * اصلاً بالا نیست** (در تولید تایمرِ systemd این کار را می‌کند:
 * `deploy/systemd/setshop-postsale.timer`). چهار حالتِ اول بی‌این بنر «موفق»
 * به‌نظر می‌رسند: دور تمام می‌شود، خروجی صفر است، و صف همان‌قدر می‌ماند که بود.
 *
 * پس بنر باید در دو خط بگوید: **چه چیزی در این دور ارسال می‌شود، و چرا چیزی
 * ارسال نمی‌شود.** «ارسال‌کننده انتخاب نشده» را که کسی نفهمد، همان چیزی است که
 * فروشنده را وادار می‌کند پیامک را دستی بفرستد و بگوید «قابلیتش هست، وصلش
 * نکرده‌اند».
 */
