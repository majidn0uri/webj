/**
 * مدلِ داده‌یِ خروجی — یک توصیف، دو نمایش.
 * ============================================================================
 *
 * ایده‌یِ اصلی این بسته همین‌جاست: **گزارش یک‌بار توصیف می‌شود، دو بار
 * نمایش داده می‌شود.** ستون‌ها، نوع‌ها، جمع‌ها و عنوان‌ها یک‌جا تعریف
 * می‌شوند و دو رندرر (پی‌دی‌اف و اکسل) از همان تعریف خروجی می‌سازند.
 *
 * چرا این مهم است؟ چون در عمل، تفاوتِ «خروجیِ اکسلِ فروشگاه» با «فاکتورِ
 * پی‌دی‌افِ همان فروش» تفاوتِ قالب است نه تفاوتِ داده. اگر هر کدام ستون‌هایِ
 * خود را تعریف کند، نخستین باری که ستونی اضافه می‌شود، یکی از دو خروجی
 * از قلم می‌افتد و کسی تا ماه‌ها نمی‌فهمد گزارشِ کاغذی با فایلِ حسابداری
 * جور نیست. اینجا آن خطا از بن بسته می‌شود.
 *
 * واحدِ پول: **ریال**، همان که در پایگاه‌داده است و همان که سامانه‌ی مؤدیان
 * می‌خواهد. نمایش به تومان تنها در جمع‌بندیِ فاکتور می‌آید (برایِ خوانایی)،
 * نه در ستون‌ها — وگرنه جمعِ ستونِ اکسل با عددِ سامانه نمی‌خواند.
 */

/** نوعِ ستون: تعیین می‌کند هم قالبِ عدد و هم ترازِ پیش‌فرض چه باشد */
export type ColumnType =
  | 'text' // رشته‌یِ فارسی/لاتین
  | 'number' // عددِ ساده (تعداد، درصد نیست)
  | 'money' // مبلغ به ریال
  | 'percent' // درصد (۹ یعنی ۹٪)
  | 'date' // تاریخِ میلادی که شمسی نمایش داده می‌شود
  | 'datetime' // تاریخ و ساعت
  | 'boolean'; // بله/خیر

export interface ReportColumn {
  /** کلید در سطرها */
  key: string;
  /** عنوانِ فارسیِ ستون */
  title: string;
  type?: ColumnType;
  /** تراز؛ اگر نیاید، از نوع برداشت می‌شود (عدد و مبلغ: راست، متن: راست) */
  align?: 'right' | 'left' | 'center';
  /**
   * پهنایِ نسبی.
   *
   * اگر نیاید، پهنا از رویِ عنوان و محتوایِ واقعی اندازه گرفته می‌شود
   * (سطرها یک‌بار اندازه می‌شوند تا هیچ ستونی نه تنگ بماند و نه بی‌دلیل پهن).
   */
  width?: number;
  /** آیا در سطرِ جمع، مجموعِ این ستون بیاید؟ */
  sum?: boolean;
}

export type CellValue = string | number | bigint | boolean | Date | null | undefined;

export interface ReportRow {
  [key: string]: CellValue;
}

/** یک جفتِ برچسب/مقدار بالایِ گزارش (بازه، صافی، ...) */
export interface ReportMeta {
  label: string;
  value: string;
}

export interface ReportSpec {
  /** عنوانِ گزارش — در اکسل هم می‌آید و هم نامِ فایل از آن ساخته می‌شود */
  title: string;
  subtitle?: string;
  /** مشخصاتِ بالایِ جدول: بازه، وضعیت، شعبه ... */
  meta?: ReportMeta[];
  columns: ReportColumn[];
  rows: ReportRow[];
  /** یادداشتِ پایینِ جدول (شرط، توضیحِ مالیاتی، ...) */
  note?: string;
  /** افقی (برایِ گزارش‌هایِ پُرستون) */
  landscape?: boolean;
  /** نامِ برگه در اکسل (پیش‌فرض: «گزارش») */
  sheetName?: string;
  /**
   * ریشه‌یِ نامِ پرونده به **لاتین** (مثلِ `orders`).
   *
   * چرا جدا از عنوان؟ چون نامِ پرونده در سربرگِ HTTP و در خطِ فرمان رد و بدل
   * می‌شود؛ «گزارشِ فروش.xlsx» در آن‌جا یا به زیرخط تبدیل می‌شود یا به
   * نویسه‌هایِ نامفهوم. عنوان هرچه می‌خواهد باشد (فارسی، برایِ چشم)، نامِ
   * پرونده لاتین می‌ماند (برایِ ماشین).
   */
  fileBase?: string;
  /** شماره‌یِ ردیف در نخستین ستون (پیش‌فرض: بله) */
  rowNumbers?: boolean;
  /** برچسبِ سطرِ جمع (پیش‌فرض: «جمع») */
  totalsLabel?: string;
  /** نشانِ کج‌رویِ سند (مثلِ «پیش‌نویس»، «تسویه‌شده») */
  watermark?: string;
  /** متنِ سمتِ راستِ پانویس (پیش‌فرض: نامِ فروشگاه) */
  footerNote?: string;
}

/* ------------------------------- فاکتور --------------------------------- */

/** یکی از دو سویِ فاکتور: فروشنده یا خریدار */
export interface PartyInfo {
  name: string;
  /** شماره‌یِ اقتصادی / شناسه‌یِ ملی */
  nationalId?: string | null;
  economicCode?: string | null;
  postalCode?: string | null;
  address?: string | null;
  phone?: string | null;
}

export interface InvoiceLine {
  /** نامِ کالا */
  title: string;
  /** کدِ کالا (SKU) */
  sku?: string | null;
  /** واحدِ اندازه‌گیری: عدد، بسته، جفت ... */
  unit?: string | null;
  quantity: number;
  /** مبلغِ واحد به ریال */
  unitPriceRial: number;
  /** تخفیفِ این سطر به ریال */
  discountRial?: number;
  /** مالیاتِ این سطر به ریال */
  taxRial?: number;
  /** جمعِ سطر به ریال — اگر نیاید، حساب می‌شود */
  totalRial?: number;
}

export interface InvoiceSpec {
  /** شماره‌یِ فاکتور (شماره‌یِ سفارش) */
  number: string;
  /** تاریخِ صدور */
  issuedAt: Date | string;
  /** وضعیت برایِ نشانِ رویِ سند و برچسب */
  status?: 'paid' | 'pending' | 'cancelled' | string;
  seller: PartyInfo;
  buyer?: PartyInfo | null;
  lines: InvoiceLine[];
  /** تخفیفِ کل به ریال (اگر رویِ سطرها پخش نشده) */
  discountRial?: number;
  /** هزینه‌یِ ارسال به ریال */
  shippingRial?: number;
  /** مالیات/عوارضِ کل به ریال */
  taxRial?: number;
  /** نرخِ ارزش‌افزوده برایِ نمایش (مثلِ ۹) */
  taxRatePercent?: number;
  /** روشِ پرداخت */
  paymentMethod?: string | null;
  /** کدِ رهگیریِ پرداخت */
  paymentReference?: string | null;
  /** یادداشتِ پایینِ فاکتور */
  note?: string | null;
  /** نشانِ رویِ سند؛ اگر نیاید از وضعیت ساخته می‌شود */
  watermark?: string | null;
  /** عنوانِ سند (پیش‌فرض: «صورتحساب فروش») */
  title?: string;
}
