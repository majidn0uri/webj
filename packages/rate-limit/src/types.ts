/**
 * قراردادهایِ مهارِ بار.
 *
 * این پرونده تنها «نوع»ها را دارد — هیچ وابستگی‌ای نه به پایگاه‌داده و نه به
 * چارچوبِ وب. چرا؟ چون مهارِ بار در سه جا به کار می‌رود: در قلابِ فستی‌فای
 * (هر درخواست)، در آزمون‌ها (بدون هیچ سروری)، و در پنل (فقط خواندنِ قاعده‌ها).
 * اگر اینجا وابستگی می‌بود، آزمونِ یک تصمیمِ ساده نیازمندِ بالا آوردنِ سامانه
 * می‌شد.
 */

/** یک قاعده‌یِ مهار — همان چیزی که مدیر در پنل می‌بیند و ویرایش می‌کند */
export interface RateRule {
  /** کلیدِ یکتا، مانندِ `auth.otp` */
  name: string;
  title: string;
  hint: string;
  /** بیشینه‌یِ شمارِ درخواست‌هایِ مجاز در یک پنجره */
  maxRequests: number;
  /** درازایِ پنجره به ثانیه */
  windowSeconds: number;
  scope: RateScope;
  store: RateStore;
  isEnabled: boolean;
}

/**
 * «چه چیزی شمرده می‌شود؟»
 *
 *   • `ip`      — فقط نشانیِ تماس‌گیرنده. برایِ خواندنِ عمومی که هویتی در کار
 *                 نیست؛ ساده‌ترین و ارزان‌ترین گزینه.
 *   • `user`    — فقط نشست/توکن. وقتی هویت هست، نشانی بی‌معناست: پشتِ یک
 *                 نشانیِ اداره، ده‌ها کارمندِ بی‌تقصیر نشسته‌اند (NAT).
 *   • `ip_user` — هر دو. برایِ کارهایِ گران (ثبتِ سفارش): هم نشستِ پُرفشار را
 *                 مهار می‌کند و هم سیلِ درخواستِ بی‌نام از یک نشانی را.
 */
export type RateScope = 'ip' | 'user' | 'ip_user';

/**
 * «شمارنده کجا نگه داشته می‌شود؟»
 *
 *   • `memory` — در همین فرآیند. هیچ کاری با پایگاه ندارد، پس برایِ مسیرهایِ
 *                پُرفشار (فهرست، جستجو، برگه‌یِ کالا) مناسب است. بهایش این
 *                است که با سه نمونه‌ی API، سقفِ عملی سه برابر می‌شود.
 *   • `db`     — در پایگاه، پس میانِ همه‌یِ نمونه‌ها یکسان است. برایِ مسیرهایِ
 *                امنیتی (ورود، کدِ یک‌بارمصرف، کوپن، ثبتِ سفارش) که کم‌تعداد
 *                اما تعیین‌کننده‌اند، همین یکسانی مهم است — نه صرفه‌جوییِ
 *                یک دهمِ میلی‌ثانیه.
 */
export type RateStore = 'memory' | 'db';

/** ورودیِ یک «گامِ شمارش» */
export interface CounterHit {
  rule: string;
  /** کلیدِ سطل (Bucket) — ترکیبِ قاعده و هویت */
  key: string;
  windowSeconds: number;
  now: Date;
}

/** نتیجه‌یِ یک گامِ شمارش */
export interface CounterValue {
  count: number;
  /** آغازِ پنجره‌ای که این شمارش در آن است (برایِ نمایشِ «چه وقت باز می‌شود») */
  windowStartedAt: Date;
}

/** جایگاهِ شمارنده — دو پیاده‌سازی دارد: حافظه و پایگاه */
export interface CounterStore {
  readonly kind: RateStore;
  incr(hit: CounterHit): Promise<CounterValue>;
  /** پاک کردنِ سطل‌ها — برایِ «آزادسازی» از پنل */
  reset(rule?: string): Promise<number>;
  /** شمارِ سطل‌هایِ زنده (برایِ دیده‌بانیِ خودِ مهارگر) */
  size(): number;
}

/** تصمیمِ مهار — آنچه قلابِ درخواست بر پایه‌اش عمل می‌کند */
export interface RateDecision {
  /** نامِ قاعده‌ای که برقرار شد (برایِ ثبت و نمایش) */
  rule: string;
  allowed: boolean;
  limit: number;
  remaining: number;
  /** چه وقت این پنجره می‌گذرد و شمارنده از نو آغاز می‌شود */
  resetAt: Date;
  /** چند ثانیه‌یِ دیگر دوباره بیایید (فقط وقتی مسدود شده) */
  retryAfterSeconds: number;
  /** کلیدِ سطل — برایِ آزادسازیِ دستی از پنل */
  bucketKey: string;
}

/** هویتِ تماس‌گیرنده — همان چیزی که سطل از آن ساخته می‌شود */
export interface CallerIdentity {
  ip: string;
  /** نشست/توکنِ خلاصه‌شده؛ برایِ بی‌نام‌ها تهی */
  sessionKey?: string;
}
