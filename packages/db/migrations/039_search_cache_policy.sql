-- مهاجرت ۰۳۹ — سیاستِ کشِ جستجو از پنل
-- ─────────────────────────────────────────────────────────────────────────────
-- چرا؟ «جستجو کند است» در این پروژه یک گزارشِ واقعی بود، و اندازه‌گیری رویِ
-- کاتالوگِ ۲۰٬۰۰۰ کالایی نشان داد یک پرسشِ داغ ۸۴ میلی‌ثانیه از وقتِ سرویس
-- می‌بَرَد (tookMs؛ بی‌شبکه و بی‌رندر). درمانِ اصلی این است که همان پرسشِ تکراری
-- دوباره از پایگاه نپرسیده شود — ولی «چقدر بماند» تصمیمِ فروشندگی است، نه
-- تصمیمِ ثابتِ کد: بعضی فروشگاه‌ها می‌خواهند قیمتِ اصلاح‌شده همان دقیقه در
-- storefront دیده شود، بعضی حاضرنده پانزده ثانیه صبر کنند. پس یک خانه در
-- تنظیمات ← پیشرفته، و صفر یعنی «کش نکن».
--
-- ON CONFLICT DO NOTHING: اگر نصب‌کننده‌ای خانه را خودش پر کرده، مقدارش را
-- بی‌سروصدا بازنویسی نمی‌کنیم.

INSERT INTO store_settings (key, value, updated_at)
VALUES ('search_cache_seconds', '15', now())
ON CONFLICT (key) DO NOTHING;

