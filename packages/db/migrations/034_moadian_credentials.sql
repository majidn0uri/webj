-- ۰۳۴ — گاوصندوقِ گواهیِ مؤدیان
--
-- مسئله‌ای که این مهاجرت می‌گشاید، «ارسال به سامانه‌یِ مالیاتی» نیست —
-- **راه‌اندازی**اش است. تا پیش از این، کلیدِ خصوصیِ امضا باید روی دیسکِ
-- سرور می‌نشست و یک متغیرِ محیطی (MOADIAN_PRIVATE_KEY_PATH) به مسیرش اشاره
-- می‌کرد. یعنی برایِ آغازِ ارسالِ واقعی — و برایِ هر تعویضِ گواهی پس از آن،
-- که معمولاً سالانه است — کسی باید به سرور دسترسیِ ترمینال می‌داشت. و این
-- دقیقاً همان کاری است که فروشنده قرار نیست انجام دهد: او همه چیز را در پنل
-- مدیریت می‌کند، بی‌یک خط کد.
--
-- پس گواهی از پنل بارگذاری می‌شود و در پایگاه می‌نشیند — اما **رمزنگاری‌شده**
-- و با کلیدی که از پایگاه نمی‌آید (SET_MASTER_KEY در محیط). چرا این وسواس؟ چون
-- کلیدِ خصوصیِ امضا یعنی «می‌توانی به نامِ این فروشگاه صورتحساب صادر کنی».
-- اگر یک نسخه‌یِ پشتیبان از پایگاه به دستِ کسی بیفتد و کلیدِ خصوصی در آن
-- باشد، رمزنگاری‌ای که کلیدش هم در همان پایگاه است چیزی را نگه نمی‌دارد.
-- جداسازیِ «کلید» از «داده‌یِ رمزشده» کمترینِ این کار است.
--
-- سه نکته‌یِ طراحی:
--   • هر رکورد یک «نسخه» است: بارگذاریِ تازه، نسخه‌یِ پیشین را باطل
--     (`revoked_at`) می‌کند و آن را نگه می‌دارد، نه اینکه پاکش کند. چرا؟
--     چون هنگامِ تعویضِ گواهی باید بتوان پرسید «تا دیروز با کدام گواهی امضا
--     می‌کردیم؟» — و چون پاک‌کردنِ چنین ردیفی یعنی هیچ مدرکی از آن نماند.
--   • اثرانگشت، سریال، تبار و تاریخ‌هایِ اعتبار در زمانِ بارگذاری استخراج و
--     **روشن** ذخیره می‌شوند. این‌ها راز نیستند، و ذخیره‌یِ روشن‌شان یعنی
--     پنل می‌تواند بدونِ گشودنِ گاوصندوق بگوید «گواهی ۱۲ روز دیگر تمام
--     می‌شود» — هشداری که باید هر روزِ ورودِ مدیر دیده شود، نه در لحظه‌یِ
--     ارسالِ ناموفق.
--   • کلیدِ عمومیِ سازمان (`public_key`) هم همین‌جا است: برایِ رمزنگاریِ
--     بسته‌یِ صورتحساب (JWE) لازم است و آن هم عوض می‌شود.

CREATE TABLE IF NOT EXISTS moadian_credentials (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- private_key | certificate | public_key
  kind           text NOT NULL CHECK (kind IN ('private_key','certificate','public_key')),
  label          text NOT NULL DEFAULT '',
  -- متنِ رمزشده (AES-256-GCM) به‌همراهِ نمک، بردار و برچسبِ اصالت
  cipher_text    text NOT NULL,
  salt           text NOT NULL,
  iv             text NOT NULL,
  tag            text NOT NULL,
  -- ویژگی‌هایِ روشن (راز نیستند؛ برایِ نمایش و هشدار)
  --
  -- دو اثرانگشت با دو معنیِ متفاوت — اشتباه‌گرفتن‌شان همان خطایی است که در
  -- نخستین اجرا رخ داد و باعث شد سامانه بگوید «کلید با گواهی جفت نیست» در
  -- حالی که بود:
  --   • fingerprint      = اثرانگشتِ **کلیدِ عمومی** (برایِ کلیدِ خصوصی:
  --                        اثرانگشتِ عمومیِ برآمده از آن). این همان است که
  --                        برایِ سنجیدنِ جفت‌بودن به کار می‌رود، چون فقط با
  --                        این تعریف است که مقدارش برایِ کلید و گواهی یکی
  --                        می‌شود — بی‌آنکه نیازی به گشودنِ گاوصندوق باشد.
  --   • cert_fingerprint = اثرانگشتِ **خودِ گواهی** (SHA-256 کلِ گواهی)؛
  --                        همان که مرجع و کارپوشه نشان می‌دهند و فروشنده با
  --                        آن گواهی را در سامانه‌یِ سازمان پیدا می‌کند.
  fingerprint      text,
  cert_fingerprint text,
  subject        text,
  issuer         text,
  serial_number  text,
  not_before     timestamptz,
  not_after      timestamptz,
  -- panel = بارگذاری از پنل؛ env = از مسیرِ فایل در محیط (فقط برایِ گزارش)
  source         text NOT NULL DEFAULT 'panel' CHECK (source IN ('panel','env')),
  created_by     uuid,
  created_at     timestamptz NOT NULL DEFAULT now(),
  revoked_at     timestamptz
);

-- تنها یک نسخه‌یِ زنده برای هر نوع: همیشه تازه‌ترین را می‌خواهیم، و این
-- شرطِ جزئی جلویِ دو نسخه‌یِ هم‌زمان (و امضایِ ناهماهنگ) را می‌گیرد.
CREATE UNIQUE INDEX IF NOT EXISTS moadian_credentials_active_uidx
  ON moadian_credentials (kind)
  WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS moadian_credentials_kind_idx
  ON moadian_credentials (kind, created_at DESC);
