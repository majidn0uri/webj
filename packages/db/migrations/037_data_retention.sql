-- ۰۳۷ — سیاستِ نگهداریِ داده (چیزهایی که باید روزی پاک شوند)
--
-- چرا لازم شد؟ سه جدول در این فروشگاه «فقط بزرگ می‌شوند»:
--   • `sms_outbox` — متنِ هر پیامک با شمارهٔ مشتری و مبلغِ سفارش در آن است؛
--     نگه‌داشتنِ پیامکِ **فرستاده‌شده** بعد از چند ماه، هم جدول را سنگین
--     می‌کند (صفحهٔ صندوق و پایش، رویِ میلیون‌ها سطرِ مرده کوئری می‌زنند) هم
--     یک پایگاهِ دادهٔ شخصیِ بی‌دلیل نگه می‌دارد.
--   • `audit_logs` — برایِ اختلافِ مالی/حقوقی لازم است، پس پیش‌فرض «هرگز
--     پاک نشود» گذاشته شده و مدیر آگاهانه روشنش می‌کند.
--   • `rate_limit_counters` / `rate_limit_events` — کلیدِ
--     `observability_retention_days` از مهاجرتِ ۰۳۳ در تنظیمات وجود داشت و
--     توضیحش هم نوشته شده بود، اما **هیچ کدی آن را نمی‌خواند** و عددِ ۷ روز
--     در `apps/api/src/rate-limit.ts` سخت‌coded بود. این دقیقاً همان چیزی است
--     که نباید در یک پنلِ «همه‌چیز از رابطِ مدیریتی» باشد: خانه‌ای که مدیر
--     پر می‌کند و اثری ندارد.
--
-- اعدادِ پیش‌فرض عمداً محافظه‌کارانه‌اند؛ ۰ یعنی «پاک نکن».
-- ─────────────────────────────────────────────────────────────────────────────

INSERT INTO store_settings (key, value, description) VALUES
  ('sms_outbox_retention_days', '60', 'پیامک‌هایِ فرستاده‌شده (و ناامیدکننده) چند روز در صف بمانند؟ ۰ یعنی هرگز پاک نشوند.'),
  ('audit_log_retention_days', '0', 'ردِّ عملیاتِ مدیریتی چند روز نگه داشته شود؟ ۰ یعنی همیشگی — برایِ اختلافِ مالی و حسابرسی.')
ON CONFLICT (key) DO NOTHING;

-- کلیدِ سوم (نگهداریِ آمارِ مهارِ بار) از ۰۳۳ هست؛ فقط توضیحش را به‌روز می‌کنیم
-- تا در پنل روشن باشد که «۰ = بی‌پایان» و این‌که عددِ خیلی کوچک یعنی «هیچ
-- وقتِ کافی برایِ دیدنِ یک حملهٔ کُند در آمار نمی‌ماند».
UPDATE store_settings
   SET description = 'ردِّ درخواست‌ها و مسدودشدن‌ها چند روز نگه داشته شود؟ ۰ یعنی پاک نشود (جدول رویِ سرورِ شلوغ زود سنگین می‌شود).'
 WHERE key = 'observability_retention_days';
