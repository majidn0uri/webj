-- ---------------------------------------------------------------------------
-- چرا لازم شد؟ چون اظهارنامه‌ی ارزش‌افزوده فروش را از «ردیف‌هایِ سفارش» جمع
-- می‌زند (درست‌ترین منبع)، و مرجوعی باید از همان جمع کم شود. برایِ کم کردن،
-- باید بدانیم از مبلغِ برگشتی چقدرش ارزش‌افزوده است — و این را نمی‌توان با
-- نسبت‌گیری دوباره به دست آورد، چون هر بار گردکردن ممکن است یک ریال جابه‌جا
-- بکند. پس سهمِ مالیات همان‌جا که محاسبه می‌شود ذخیره می‌شود.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE customer_return_items
  ADD COLUMN IF NOT EXISTS refund_tax_rial bigint NOT NULL DEFAULT 0
    CHECK (refund_tax_rial >= 0);

-- یکپارچگی: سهمِ مالیات نمی‌تواند از کلِ مبلغِ برگشتیِ همان ردیف بیشتر باشد
ALTER TABLE customer_return_items
  DROP CONSTRAINT IF EXISTS customer_return_items_tax_le_refund_chk;
ALTER TABLE customer_return_items
  ADD CONSTRAINT customer_return_items_tax_le_refund_chk
    CHECK (refund_tax_rial <= refund_rial);
