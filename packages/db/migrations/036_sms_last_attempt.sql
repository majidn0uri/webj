-- ۰۳۶ — ردّپایِ «آخرینِ تلاشِ واقعی» رویِ هر پیامک
--
-- چرا ستونِ تازه لازم شد؟ صفحهٔ پایشِ پنل می‌پرسد «چند دقیقه است صف تکان
-- نخورده؟» و تنها پاسخِ درست، زمانِ خودِ تماس است. بی‌این ستون، کد مجبور بود
-- از `available_at» حدس بزند — و آن «زمانِ تلاشِ بعدی» است، یعنی در پیامِ
-- ناموفق به آینده نگاه می‌کند؛ حدس‌زدنِ «کارگر زنده است» از رویش یعنی یک
-- قطعیِ ۲۰ دقیقه‌ایِ سامانه، خوابِ کارگر گزارش نشود (و برعکس). پس یک
-- `timestamptz` صریح، نه یک فرمولِ حدسی رویِ ستونِ دیگر.
--
-- پیامِ `pending` که هرگز تلاش نشده `NULL` می‌ماند — و همین درست است: نبودِ
-- تکانه، خودش همان چیزی است که مدیر باید ببیند.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE sms_outbox ADD COLUMN IF NOT EXISTS last_attempt_at timestamptz NULL;

-- بازپُریِ داده‌یِ موجود: «فرستاده‌شده» زمانِ ارسالِ خودش را می‌گیرد؛
-- ناموفق/ناامیدکننده/در‌حال‌ارسال، نزدیک‌ترینِ چیزِ موجود (نوبتِ تلاش) را — و
-- اگر نوبت در آینده بود، همان «اکنون» ثبت می‌شود که تازه‌تر از واقعیت است اما
-- هشدارِ دروغِ «کارگر خواب است» نمی‌سازد.
UPDATE sms_outbox
   SET last_attempt_at = CASE
       WHEN status = 'sent' THEN COALESCE(sent_at, created_at)
       -- «نوبتِ بعد» = زمانِ تلاش + فاصلهٔ بک‌آف؛ پس با کم‌کردنِ همان فاصله
       -- (یک دقیقه، محافظه‌کارانه) به لحظهٔ تلاش بازمی‌گردیم و «کارگر تازه
       -- بود» گزارش نمی‌شود
       WHEN status IN ('failed','dead','sending')
         THEN GREATEST(LEAST(COALESCE(available_at, now()), now()) - interval '11 minutes', created_at)
       ELSE NULL
   END
 WHERE last_attempt_at IS NULL;

-- فهرستِ کمکی برایِ «آخرینِ تکانهٔ صف» — یک MAX رویِ کلِ جدول، در فروشگاهِ
-- پرمخاطب بی‌فهرست یعنی هر بازکردنِ صفحه یک seq scan
CREATE INDEX IF NOT EXISTS ix_sms_outbox_last_attempt
    ON sms_outbox (last_attempt_at DESC NULLS LAST);
