-- ۰۳۱ — ترتیبِ تنوع‌ها و سواچِ رنگ
--
-- یک کاستیِ خاموش: جدولِ تنوع‌ها هیچ ستونِ ترتیبی نداشت. یعنی رنگ‌ها در
-- برگه‌یِ کالا به همان ترتیبی می‌آمدند که پایگاه برمی‌گرداند — که در عمل
-- یعنی «به ترتیبِ شانس». فروشنده‌ای که می‌خواهد «مشکی» نخستین گزینه باشد
-- (پرفروش‌ترین)، راهی نداشت جز تغییرِ نام یا شناسه.
--
-- با آمدنِ سواچِ رنگ، این کاستی دیده می‌شود: سواچ‌ها در یک ردیف‌اند و
-- ترتیبشان همان چیزی است که نخست به چشم می‌آید. پس ترتیب را به خودِ
-- فروشنده می‌سپاریم.
-- ─────────────────────────────────────────────────────────────────────────────

BEGIN;

ALTER TABLE product_variants
  ADD COLUMN IF NOT EXISTS sort_order integer NOT NULL DEFAULT 0;

-- جستجویِ پرکاربرد: تنوع‌هایِ یک کالا به ترتیبِ چیدمان
CREATE INDEX IF NOT EXISTS ix_variants_product_order
  ON product_variants (product_id, sort_order, sku);

COMMIT;
