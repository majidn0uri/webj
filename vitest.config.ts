import { defineConfig } from 'vitest/config';

/**
 * هر فایلِ آزمون یک نمونه‌ی PGlite (WASM) بالا می‌آورد که صدها مگابایت حافظه
 * می‌خواهد. اجرایِ کاملاً موازیِ ۱۰ فایل در دستگاه‌هایِ کم‌حافظه (۲ گیگابایت)
 * باعث می‌شود کارگرها با خطایِ «Worker exited unexpectedly» کشته شوند —
 * که به‌اشتباه به‌صورتِ «تستِ ناپایدار» دیده می‌شود.
 *
 * بنابراین هم‌زمانی محدود شده است؛ اجرا کمی طولانی‌تر اما کاملاً قطعی است.
 */
export default defineConfig({
  // tsconfigِ پروژه `jsx: preserve` دارد (نکست خودش JSX را ترجمه می‌کند)؛
  // esbuildِ وی‌تست «preserve» را نمی‌فهمد و به‌اشتباه به حالتِ کلاسیک
  // (React.createElement) برمی‌گردد. runtime خودکار هم‌خوانیِ درست را می‌دهد.
  esbuild: { jsx: 'automatic' },
  test: {
    include: ['packages/**/*.test.ts', 'apps/**/*.test.ts'],
    testTimeout: 60_000,
    hookTimeout: 60_000,
    /**
     * چرا DB_URL اینجا « memory:// » می‌شود، حتی اگر در پوسته مقدار داشته باشد؟
     *
     * چون یک `export DB_URL=…` یِ فراموش‌شده، آزمون‌ها را به **پایگاهِ
     * توسعه** می‌برد: هر اجرا بیست‌وچهار سفارشِ «ORD-…» در پایگاهِ واقعی می‌نشاند،
     * جدولِ سفارش‌هایِ پنل را با ردیف‌هایِ آزمایشی شلوغ می‌کند و خروجیِ گزارش‌ها
     * را به عددی بی‌ربط می‌اندازد — بی‌آنکه هیچ آزمونی قرمز شود. این یک
     * «خرابیِ خاموش» است: سامانه سالم به‌نظر می‌رسد، اما داده‌اش کثیف است.
     *
     * مقدارِ اینجا بر هرچه در پوسته باشد چیره می‌شود (وی‌تست آن را در
     * process.envِ کارگر می‌نشاند)، پس آزمون همواره پایگاهِ درون‌حافظه‌یِ
     * خودش را می‌سازد و با پایانش پاک می‌شود. اگر کسی روزی واقعاً بخواهد
     * آزمونی را روی پایگاهِ واقعی اجرا کند، باید آگاهانه همین خط را عوض کند.
     */
    env: { DB_URL: 'memory://' },
    // حداکثر ۲ کارگرِ هم‌زمان: تعادل میانِ سرعت و مصرفِ حافظه
    maxWorkers: 2,
    minWorkers: 1,
    // فایل‌ها یکی‌یکی اجرا شوند تا هیچ دو نمونه‌ی پایگاه‌داده هم‌زمان نباشد
    fileParallelism: false,
    pool: 'forks',
    poolOptions: {
      forks: { singleFork: false },
    },
  },
});
