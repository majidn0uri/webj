import { z } from 'zod';

/**
 * تنظیمات — اعتبارسنجی در زمانِ اجرا آغاز می‌شود (بخش C-2).
 * هیچ متغیرِ محیطی بدون اعتبارسنجی وارد برنامه نمی‌شود تا خطاهایِ بی‌صدا در تولید نداشته باشیم.
 */
const EnvSchema = z.object({
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  PORT: z.coerce.number().int().positive().default(3000),
  /**
   * نشانی‌ای که API روی آن گوش می‌دهد.
   *
   * پیش‌فرض وابسته به محیط است، چون نیازِ این دو یکی نیست:
   *   • تولید ('production'): '127.0.0.1' — API پشتِ nginx است و هیچ
   *     کلاینتی نباید مستقیماً به پورتِ ۳۰۰۰ برسد.
   *   • توسعه/پیش‌نمایش: '0.0.0.0' — وگرنه از بیرونِ محیطِ اجرا (مرورگر،
   *     موبایل، یا پنلِ پیش‌نمایش) اصلاً دیده نمی‌شود.
   *
   * مقدار را همیشه می‌توان با API_HOST صریحاً تعیین کرد؛ این فقط پیش‌فرض است.
   */
  API_HOST: z
    .string()
    .default(process.env.NODE_ENV === 'production' ? '127.0.0.1' : '0.0.0.0'),
  /**
   * 'memory://'  → درون‌فرآیندی (فقط تست؛ با خروج پاک می‌شود)
   * './.data/pg' → روی دیسک (پیش‌فرضِ توسعه؛ بینِ اجراها می‌ماند)
   * 'postgres://…' → PostgreSQL واقعی (تولید)
   */
  DB_URL: z.string().default('./.data/pg'),
  /**
   * کلیدِ امضای توکن.
   *
   * در تولید **باید** از محیط تزریق شود: اگر نباشد، برنامه اصلاً بالا
   * نمی‌آید (پایین‌تر بررسی شده است). چرا این‌قدر سخت‌گیرانه؟ چون یک کلیدِ
   * پیش‌فرضِ عمومی یعنی هر کس می‌تواند برایِ خودش توکنِ مدیر امضا کند — و
   * آن توکن درِ همه‌چیز است: کالا، قیمت، سفارش، گواهیِ مؤدیان. بدترین
   * سناریویِ امنیتیِ این پروژه همین است، و هیچ لاگی نشانش نمی‌دهد.
   */
  JWT_SECRET: z.string().min(16).default('dev-only-secret-change-me-in-production'),
  /**
   * مبدأهایِ مجاز برایِ درخواست‌هایِ میان‌دامنه‌ای (با ویرگول جدا شوند).
   *
   * پیش‌فرض: تهی، یعنی فقط همان مبدأی که فروشگاه رویِ آن است (`APP_URL`).
   * پذیرفتنِ «همه‌یِ مبدأها» همراه با کوکی (`credentials`) یعنی هر سایتی
   * که قربانی باز کند می‌تواند با نشستِ او از API بخواند.
   */
  CORS_ORIGINS: z.string().default(''),
  /** نرخِ ارزش‌افزوده بر حسبِ واحدِ درصد (۹۰۰ = ۹٪). باید از تنظیماتِ پنل هم قابل تغییر باشد. */
  VAT_RATE_BP: z.coerce.number().int().min(0).max(10_000).default(900),
  /** هیچ درخواستی به دامنه‌ی خارجی (بخش AA) — این پرچم در تست‌ها استفاده می‌شود */
  STRICT_IRAN_ONLY: z
    .string()
    .default('true')
    .transform((v) => v === 'true'),

  /* ---------- درگاهِ پرداختِ ایرانی ---------- */
  /** نشانیِ عمومیِ فروشگاه — درگاه مشتری را به آن برمی‌گرداند و callback از آن ساخته می‌شود */
  APP_URL: z.string().url().default('http://127.0.0.1:3100'),
  /** کدام درگاه پیش‌فرض است: sandbox | zarinpal | idpay */
  PAYMENT_GATEWAY: z.enum(['sandbox', 'zarinpal', 'idpay']).default('sandbox'),
  /** اجازه‌ی درگاهِ آزمایشی در تولید (به‌طورِ پیش‌فرض خاموش است) */
  PAYMENT_ALLOW_SANDBOX: z.string().default('0').transform((v) => v === '1'),
  ZARINPAL_MERCHANT_ID: z.string().default(''),
  /** IRR = ریال (پیش‌فرض)، IRT = تومان */
  ZARINPAL_CURRENCY: z.enum(['IRR', 'IRT']).default('IRR'),
  ZARINPAL_SANDBOX: z.string().default('0').transform((v) => v === '1'),
  IDPAY_API_KEY: z.string().default(''),
  IDPAY_SANDBOX: z.string().default('1').transform((v) => v === '1'),

  /* ---------- مهارِ بار و دیده‌بانی ---------- */
  /**
   * کلیدِ تماسِ درونی (وب → API).
   *
   * چرا لازم است؟ چون صفحه‌هایِ فروشگاه در سرورِ نکست ساخته می‌شوند: یعنی
   * ده‌ها درخواستِ «برایِ یک خریدار»، از **یک** نشانی (خودِ وب) به API
   * می‌رسند. اگر آن‌ها را با نشانی بشماریم، سقفِ هر خریدار سهمِ همه می‌شود و
   * در نخستین شلوغی، فروشگاه خودش را می‌بندد.
   *
   * پس وب این کلید را در سرآیند می‌فرستد و API درخواست‌هایی که آن را دارند،
   * از سقف‌هایِ «حاشیه‌ای» (خواندنِ عمومی) معاف می‌کند — اما همچنان سقف‌هایِ
   * کسب‌وکاری (ورود، سفارش، کوپن) را اِعمال می‌کند، چون آن‌ها با نشستِ خریدار
   * شمرده می‌شوند نه با نشانیِ وب.
   */
  INTERNAL_API_TOKEN: z.string().default(''),
  /**
   * نشانی‌هایی که «پروکسیِ جلویِ API» هستند و سرآیندهایِ
   * `X-Forwarded-For` / `X-Real-IP` آن‌ها باور می‌شود (با ویرگول جدا شوند؛
   * پیشوندِ شبکه هم می‌شود نوشت: `172.17.0.0/16`).
   *
   * چرا فهرستِ صریح و نه «باورکردنِ هر XFF»؟ چون نخستینِ مقدارِ XFF را خودِ
   * کلاینت می‌نویسد؛ اعتمادِ کور یعنی مهارِ نرخ با یک سرآیند دور زده می‌شود و
   * لاگِ امنیتی (`login_attempts`، رویدادهایِ مهار، `payments.meta`) قابلِ جعل
   * است. `apps/api/src/client-ip.ts` سندِ کاملِ این تصمیم است.
   *
   * تهی یعنی «API هیچ‌وقت پشتِ پروکسی نیست» — بی‌خطرترین حالت، و پیش‌فرضِ
   * توسعه. پیش‌فرضِ تولید `127.0.0.1,::1` است، چون استقرارِ مستندات nginx را
   * رویِ همان ماشین می‌نشاند.
   */
  TRUSTED_PROXY_IPS: z
    .string()
    .default(process.env.NODE_ENV === 'production' ? '127.0.0.1,::1' : ''),
  /**
   * آیا تماسِ درونیِ وب (با `INTERNAL_API_TOKEN`) مجاز است نشانیِ مشتری را در
   * `x-set-client-ip` بنویسد؟ روشن است، و بی‌خطر، چون بی‌کلیدِ درونی این
   * سرآیند هیچ اعتباری ندارد (آزمون در `client-ip.test.ts`).
   *
   * چرا لازم است؟ چون Next با `rewrites` سرآیندها را عبور **نمی‌دهد**: اگر این
   * خاموش باشد، همه‌یِ خریدارانِ فروشگاه برایِ API یک نشانی‌اند (`127.0.0.1`) و
   * سقف‌هایِ کسب‌وکاری که «با نشست» شمرده می‌شوند، برایِ خریدارانِ واردنشده
   * رویِ یک سطلِ مشترک می‌نشینند — یعنی مثلاً ۱۰ سفارش در ساعت برایِ **کلِ
   * فروشگاه**. این همان چیزی است که در آزمونِ بارِ `--mix checkout` دیدیم.
   */
  TRUST_WEB_CLIENT_IP: z
    .string()
    .default('true')
    .transform((v) => v === 'true'),
    /** مهارِ بار در آغاز روشن است؛ مدیر در پنل می‌تواند خاموشش کند (کلیدِ اضطراری) */
  RATE_LIMIT_ENABLED: z.string().default('1').transform((v) => v === '1'),
  /** لاگِ ساخت‌یافتهٔ درخواست‌ها (یک خطِ JSON برایِ هر درخواست) */
  REQUEST_LOG: z.string().default('1').transform((v) => v === '1'),
});

export type AppConfig = z.infer<typeof EnvSchema>;

/** کلیدِ شناخته‌شده‌یِ توسعه — در تولید پذیرفته نیست، هرچند صریحاً تنظیم شده باشد */
const DEV_SECRET = 'dev-only-secret-change-me-in-production';

export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const parsed = EnvSchema.safeParse(env);
  if (!parsed.success) {
    const details = parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`);
    throw new Error(`تنظیمات نامعتبر است:\n${details.join('\n')}`);
  }

  const config = parsed.data;

  // ── دروازه‌یِ تولید: چیزی که بی‌صدا فاجعه می‌سازد، باید با صدا جلویش را گرفت ──
  //
  // دو قانونِ ساده، هر دو «شکستِ بلند»:
  //  ۱. در production کلیدِ امضا باید از محیط آمده باشد؛ پیش‌فرض پذیرفته نیست.
  //  ۲. کلیدِ توسعه حتی اگر دستی تنظیم شود، در production مردود است
  //     (اشتباهِ رایج: رونوشتِ پرونده‌یِ env از محیطِ توسعه به سرور).
  //
  // چرا «بالا نیامدن» بهتر از «بالا آمدن با کلیدِ ضعیف» است؟ چون حالتِ دوم
  // هیچ نشانی نمی‌دهد: همه‌چیز کار می‌کند، تا روزی که کسی با توکنِ جعلی وارد
  // می‌شود و هیچ ردی از ورودش نیست.
  if (config.NODE_ENV === 'production') {
    const supplied = env.JWT_SECRET !== undefined && env.JWT_SECRET !== '';
    if (!supplied) {
      throw new Error(
        'در تولید باید JWT_SECRET را در محیط تعیین کنید. ' +
          'بالا آمدن با کلیدِ پیش‌فرض یعنی هر کس می‌تواند توکنِ مدیر امضا کند.',
      );
    }
    if (env.JWT_SECRET === DEV_SECRET || env.JWT_SECRET!.length < 32) {
      throw new Error(
        'JWT_SECRET در تولید معتبر نیست: یا همان کلیدِ توسعه است یا کوتاه‌تر از ۳۲ نویسه. ' +
          'یک رشته‌یِ تصادفیِ بلند بسازید (مثلاً: openssl rand -base64 48).',
      );
    }
  }

  return config;
}

/** مبدأهایِ مجاز برایِ CORS (از تنظیمات یا همان نشانیِ فروشگاه) */
export function corsOrigins(config: AppConfig): string[] {
  const list = config.CORS_ORIGINS.split(',')
    .map((item) => item.trim().replace(/\/$/, ''))
    .filter(Boolean);
  return list.length ? list : [config.APP_URL.replace(/\/$/, '')];
}

